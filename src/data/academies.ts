export const getAcademy = (id: string): Academy | undefined =>
  ACADEMIES.find((a) => a.id === id);

export const getModule = (academyId: string, moduleId: string) =>
  ACADEMIES.find((a) => a.id === academyId)?.modules.find((m) => m.id === moduleId);

export const getTopic = (moduleId: string, topicId: string) => {
  for (const academy of ACADEMIES) {
    for (const mod of academy.modules) {
      if (mod.id === moduleId) {
        return mod.topics.find((t) => t.id === topicId);
      }
    }
  }
};

